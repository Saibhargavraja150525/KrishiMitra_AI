def get_farming_advice(question: str, crop: str = "Other", village: str = ""):
    q = question.lower()

    if any(word in q for word in ["పసుపు", "yellow", "ఆకులు", "ఆకు"]):
        answer = TELUGU_RESPONSES["yellow"]
    elif any(word in q for word in ["నీరు", "నీటిపారుదల", "water", "irrigation"]):
        answer = TELUGU_RESPONSES["water"]
    elif any(word in q for word in ["పురుగు", "తెగులు", "pest", "insect"]):
        answer = TELUGU_RESPONSES["pest"]
    else:
        answer = TELUGU_RESPONSES["general"]

    context = f"\n\nమీ ప్రొఫైల్: పంట – {crop}"
    if village:
        context += f", ప్రాంతం – {village}"

    return answer + context, "Rule-based demo (not an LLM)"
